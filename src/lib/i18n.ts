export type Lang = "ar" | "en";
export type LangKey = keyof typeof translations["ar"];

export function t(lang: Lang, key: LangKey, ...args: string[]): string {
  const template = (translations[lang] as Record<string, string>)[key]
    ?? (translations.ar as Record<string, string>)[key]
    ?? key;
  return args.reduce((s, arg, i) => s.replace(`{${i}}`, arg), template);
}
